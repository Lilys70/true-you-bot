# Минимальный и максимальный балл ответа по шкале.
MIN_ANSWER = min(score for _, score in ANSWER_OPTIONS)
MAX_ANSWER = max(score for _, score in ANSWER_OPTIONS)


def apply_answer(question: dict, answer: int) -> int:
    """Переводит ответ пользователя в зачётный балл.

    Для прямых вопросов балл берётся как есть, для обратных (reverse)
    инвертируется по формуле 4 - ответ: «очень часто» в утверждении
    «я часто чувствую себя неудачником» снижает итоговый балл.

    Инверсия делается ровно один раз — при приёме ответа в bot.py,
    поэтому calculate_result() получает уже приведённые баллы.
    """
    if not MIN_ANSWER <= answer <= MAX_ANSWER:
        raise ValueError(
            f"Ответ вне шкалы {MIN_ANSWER}-{MAX_ANSWER}: {answer}"
        )
    if question["type"] == "reverse":
        return MAX_ANSWER - answer
    return answer


def calculate_result(scores: list[int]) -> dict:
    """Считает итог теста и определяет уровень самооценки.

    scores — список зачётных баллов, по одному на каждый вопрос:
    для прямых вопросов это ответ пользователя, для обратных —
    уже инвертированный через apply_answer().

    Возвращает словарь с ключами: level, total, max_total,
    title, description, advice.
    """
    if len(scores) != len(QUESTIONS):
        raise ValueError(
            f"Нужно {len(QUESTIONS)} баллов, получено {len(scores)}"
        )
    for score in scores:
        if not MIN_ANSWER <= score <= MAX_ANSWER:
            raise ValueError(
                f"Балл вне шкалы {MIN_ANSWER}-{MAX_ANSWER}: {score}"
            )

    total = sum(scores)
    for level, item in RESULTS.items():
        low, high = item["range"]
        if low <= total <= high:
            return {
                "level": level,
                "total": total,
                "max_total": len(QUESTIONS) * MAX_ANSWER,
                "title": item["title"],
                "description": item["description"],
                "advice": item["advice"],
            }
    raise ValueError(f"Для суммы {total} не найден уровень результата")

